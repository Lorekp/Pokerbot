def build_river_corpus():
    """40 Leg-B river states matched to their exact Q_BR (audit_river_k_headroom form)."""
    from native_exploit_equiv import SubgameRoot, _PBS
    from pokerbot.engine.np_engine import SEAT_ALLIN

    states = pickle.load(open(REPO / "artifacts" / "audit_river_states.pkl", "rb"))
    states = [s for s in states
              if not any(int(x) == int(SEAT_ALLIN) for x in np.asarray(s["env"].seat_status))]
    by_deal = {(int(s["deal"]), int(s["hero"])): s for s in states}
    legb = json.load(open(REPO / "artifacts" / "audit_river_exact.json"))
    results_b = legb["results"] if "results" in legb else legb

    corpus = []
    for r in results_b:
        st = by_deal.get((int(r["deal"]), int(r["hero"])))
        if st is None:
            continue
        env, hero = st["env"], int(st["hero"])
        q = {int(a): float(v) for a, v in r["q_br_chips"].items()}
        root = SubgameRoot(env=env, hero_seat=hero, pbs_vector=np.zeros(1),
                           legal_mask=np.ones(1, dtype=bool))
        corpus.append({
            "id": f"river_d{r['deal']}_h{r['hero']}_s{r['state']}",
            "cls": "river", "street": 3,
            "root": root, "pbs": _PBS(env),
            "q_acts": sorted(q.keys()), "q": q, "v_br": max(q.values()),
            "pot_bb": float(r["pot_bb"]),
        })
    return corpus


def build_live_probe_corpus(n=15):
    """The 15 live-probe game-flow states (search_roots.pkl[:15])."""
    from native_exploit_equiv import build_root
    roots = pickle.load(open(REPO / "artifacts" / "search_roots.pkl", "rb"))[:n]
    corpus = []
    for i, rec in enumerate(roots):
        root, pbs = build_root(rec)
        corpus.append({
            "id": f"liveprobe_{i:02d}", "cls": "live_probe",
            "street": int(rec.get("street", -1)),
            "root": root, "pbs": pbs,
        })
    return corpus


def build_multiway_flop_corpus(snap, want, max_hands, seed):
    """Seeded deterministic self-play -> >=`want` multiway RAISED-pot flop states.

    Reuses bench_search_capture.CapturingHero (the helper that produced search_roots.pkl):
    a blueprint SearchAgent hero + 5 calling stations, play_hand loop, capture flop decision
    nodes; keep those with >=3 SEAT_LIVE and a raised pot (max committed_total > 1 BB).
    """
    from bench_search_capture import CapturingHero
    from native_exploit_equiv import build_root
    from pokerbot.engine import game
    from pokerbot.engine.game import GameState
    from pokerbot.engine.np_engine import SEAT_LIVE
    from pokerbot.eval.bots import build_bot

    rng = random.Random(seed)
    hero_seat = 0
    hero = CapturingHero(
        use_pluribus_search=True, blueprint_snapshot=snap, search_preflop=True,
        hero_seat=hero_seat, pluribus_leaf_select="uniform",
    )
    hero.solver.config.max_iterations = 4      # cheap capture; real solves happen in the sweep
    hero.solver.config.time_budget_ms = 10 ** 9
    hero.solver.config.leaf.rollout_samples = 1
    hero.capture_streets = {1}                 # flop only
    others = {s: build_bot("calling_station", rng) for s in range(1, 6)}

    picked, seen = [], set()
    for h in range(max_hands):
        hero.reset_hand(hero_seat)
        policies = {hero_seat: hero}
        policies.update(others)
        state = GameState.new_hand(rng=rng)
        try:
            game.play_hand(policies, state=state, rng=rng)
        except Exception as e:  # noqa: BLE001
            log(f"  [gen] hand {h} aborted: {e!r}")
        for c in hero.captured:
            env = c["env"]
            st = np.asarray(env.seat_status)
            nlive = int((st == int(SEAT_LIVE)).sum())
            ct = np.asarray(env.committed_total)
            raised = int(ct.max()) > BB_CHIPS
            if int(c["street"]) == 1 and nlive >= 3 and raised:
                sig = (tuple(int(x) for x in np.asarray(env.board)),
                       tuple(int(x) for x in ct),
                       tuple(int(x) for x in np.asarray(env.holes[hero_seat])))
                if sig in seen:
                    continue
                seen.add(sig)
                picked.append(c)
        hero.captured = []
        if len(picked) >= want:
            break
    log(f"  [gen] captured {len(picked)} multiway raised-pot flop states over <= {h+1} hands")

    corpus = []
    for i, rec in enumerate(picked[:want]):
        root, pbs = build_root(rec)
        env = rec["env"]
        corpus.append({
            "id": f"mwflop_{i:02d}", "cls": "mw_flop", "street": 1,
            "root": root, "pbs": pbs,
            "n_live": int((np.asarray(env.seat_status) == 2).sum()),
            "pot_chips": int(np.asarray(env.committed_total).sum()),
        })
    return corpus


# --------------------------------------------------------------------------- solver
def build_solver(snap):
    import engine_ab_h2h as ab
    pf = ab._build_policy({"iterations": 2000}, snap, SEED, str(REPO))
    sv = [c.cell_contents for c in pf.__closure__
          if hasattr(getattr(c, "cell_contents", None), "config")][0]
    sv.config.native = True
    return sv


def solve_fixed(sv, item, K):
    """Run exactly K native iterations (wall budget removed so the fit never triggers)."""
    sv.config.max_iterations = int(K)
    sv.config.time_budget_ms = 10 ** 12
    sv.config.single_table_iter_floor = None
    sv.config.single_table_budget_ms = None
    t0 = time.perf_counter()
    res = sv.solve(item["root"], item["pbs"])
    ms = (time.perf_counter() - t0) * 1000.0
    probs = np.asarray(res.action_probs, dtype=np.float64)
    return probs, int(res.iterations), ms, str(res.metadata.get("served", "?"))


def solve_budget(sv, item, budget_ms):
    """Budget-fit: K=200 probe + budget-fitted main (cap high so wall budget binds)."""
    sv.config.max_iterations = int(BUDGET_CAP)
    sv.config.time_budget_ms = int(budget_ms)
    sv.config.single_table_iter_floor = None
    sv.config.single_table_budget_ms = None
    t0 = time.perf_counter()
    res = sv.solve(item["root"], item["pbs"])
    ms = (time.perf_counter() - t0) * 1000.0
    return int(res.iterations), ms, bool(res.metadata.get("budget_bound", False))


# --------------------------------------------------------------------------- gates
def _median(xs):
    return float(np.median(np.asarray(xs, dtype=np.float64))) if xs else float("nan")


def _dist(xs):
    if not xs:
        return {"n": 0}
    a = np.asarray(xs, dtype=np.float64)
    return {
        "n": int(a.size), "min": float(a.min()), "p10": float(np.percentile(a, 10)),
        "median": float(np.median(a)), "mean": float(a.mean()),
        "p90": float(np.percentile(a, 90)), "max": float(a.max()),
    }


def compute_gates(results, has_ref):
    ks = [str(k) for k in KS]
    # Reference key: the registered K=50000 when available, else the largest completed K as a
    # clearly-labelled PROXY so the Phase-A partial is still informative.
    ref_key = str(KREF) if has_ref else str(KS[-1])
    proxy = not has_ref
    gates = {}

    # -------- S1(a): L1-vs-ref monotone + argmax agreement @K2000 --------
    l1_by_k = {k: [] for k in ks}
    argmax_agree_2000 = []
    for r in results:
        fx = r["fixed"]
        ref = fx.get(ref_key)
        if ref is None:
            continue
        pref = np.asarray(ref["probs"], dtype=np.float64)
        amax_ref = int(np.argmax(pref))
        for k in ks:
            if k in fx and k != ref_key:
                p = np.asarray(fx[k]["probs"], dtype=np.float64)
                nn = min(p.size, pref.size)
                l1_by_k[k].append(float(np.abs(p[:nn] - pref[:nn]).sum()))
        if "2000" in fx and "2000" != ref_key:
            p2 = np.asarray(fx["2000"]["probs"], dtype=np.float64)
            argmax_agree_2000.append(int(np.argmax(p2) == amax_ref))
    ks_cmp = [k for k in ks if k != ref_key]
    med_l1 = {k: _median(l1_by_k[k]) for k in ks_cmp}
    seq = [med_l1[k] for k in ks_cmp]
    monotone = all(seq[i] >= seq[i + 1] - 1e-9 for i in range(len(seq) - 1)) if len(seq) > 1 else None
    agree = float(np.mean(argmax_agree_2000)) if argmax_agree_2000 else float("nan")
    if proxy:
        gates["S1a"] = {
            "verdict": "PARTIAL",
            "note": f"no K=50000 ref yet; metrics vs K={ref_key} PROXY reference",
            "median_L1_vs_proxy_by_K": {k: round(med_l1[k], 5) for k in ks_cmp},
            "median_L1_monotone_shrinking": monotone,
            "argmax_agreement_at_K2000_vs_proxy": round(agree, 4),
            "n_states": len(argmax_agree_2000),
        }
    else:
        s1a_pass = bool(monotone and agree >= 0.95)
        gates["S1a"] = {
            "verdict": "PASS" if s1a_pass else "FAIL",
            "median_L1_vs_ref_by_K": {k: round(med_l1[k], 5) for k in ks_cmp},
            "median_L1_monotone_shrinking": bool(monotone),
            "argmax_agreement_at_K2000": round(agree, 4),
            "argmax_threshold": 0.95,
            "n_states": len(argmax_agree_2000),
        }

    # -------- S1(b): river EVloss headroom median <= 25 mbb --------
    headrooms = []
    detail = []
    for r in results:
        if r["cls"] != "river":
            continue
        fx = r["fixed"]
        if "2000" not in fx or ref_key not in fx or "2000" == ref_key:
            continue
        q = {int(a): float(v) for a, v in r["q"].items()}
        acts = sorted(q.keys())
        v_br = float(r["v_br"])

        def evloss(probs):
            p = np.asarray([max(probs[a], 0.0) if a < len(probs) else 0.0 for a in acts],
                           dtype=np.float64)
            s = p.sum()
            p = p / s if s > 1e-9 else p
            ev = float(sum(pi * q[a] for pi, a in zip(p, acts)))
            return (v_br - ev) * MBB_PER_CHIP

        l2000 = evloss(np.asarray(fx["2000"]["probs"], dtype=np.float64))
        lref = evloss(np.asarray(fx[ref_key]["probs"], dtype=np.float64))
        headrooms.append(l2000 - lref)
        detail.append({"id": r["id"], "evloss_k2000_mbb": round(l2000, 3),
                       f"evloss_k{ref_key}_mbb": round(lref, 3), "headroom_mbb": round(l2000 - lref, 3)})
    med_hr = _median(headrooms)
    if proxy:
        gates["S1b"] = {
            "verdict": "PARTIAL",
            "note": f"no K=50000 ref yet; headroom vs K={ref_key} PROXY (real gate is vs 50000)",
            "median_headroom_vs_proxy_mbb": round(med_hr, 3) if headrooms else None,
            "n_river_states": len(headrooms),
        }
    else:
        s1b_pass = bool(med_hr <= 25.0)
        gates["S1b"] = {
            "verdict": "PASS" if s1b_pass else "FAIL",
            "median_headroom_mbb": round(med_hr, 3), "threshold_mbb": 25.0,
            "mean_headroom_mbb": round(float(np.mean(headrooms)), 3) if headrooms else None,
            "n_river_states": len(headrooms), "per_state": detail,
        }

    # -------- S1(c): K=2000 fits both envelopes on >=90% + K_main dist per class --------
    both_ok, live_ok, arena_ok = [], [], []
    kmain_live = {"river": [], "live_probe": [], "mw_flop": []}
    kmain_arena = {"river": [], "live_probe": [], "mw_flop": []}
    for r in results:
        bf = r.get("budget")
        if not bf:
            continue
        kl = int(bf["live_2500"]["k_main"])
        ka = int(bf["arena_800"]["k_main"])
        kmain_live[r["cls"]].append(kl)
        kmain_arena[r["cls"]].append(ka)
        live_ok.append(int(kl >= 2000))
        arena_ok.append(int(ka >= 2000))
        both_ok.append(int(kl >= 2000 and ka >= 2000))
    frac_both = float(np.mean(both_ok)) if both_ok else float("nan")
    s1c_pass = bool(frac_both >= 0.90)
    gates["S1c"] = {
        "verdict": "PASS" if s1c_pass else "FAIL",
        "frac_states_K2000_fits_both_envelopes": round(frac_both, 4),
        "frac_live_2500_fits_K2000": round(float(np.mean(live_ok)), 4) if live_ok else None,
        "frac_arena_800_fits_K2000": round(float(np.mean(arena_ok)), 4) if arena_ok else None,
        "threshold": 0.90, "n_states": len(both_ok),
        "kmain_live_2500_by_class": {c: _dist(v) for c, v in kmain_live.items()},
        "kmain_arena_800_by_class": {c: _dist(v) for c, v in kmain_arena.items()},
    }
    return gates


def write_out(meta, results, has_ref):
    slim = []
    for r in results:
        slim.append({k: v for k, v in r.items() if k not in ("root", "pbs", "q")})
    payload = {"meta": meta, "gates": compute_gates(results, has_ref), "results": slim}
    tmp = str(OUT) + ".tmp"
    with open(tmp, "w") as f:
        json.dump(payload, f, indent=1)
    os.replace(tmp, OUT)


# --------------------------------------------------------------------------- main
def main() -> int:
    open(PROG, "w").close()
    from pokerbot.search import native_solver as _ns
    from pokerbot.search.pluribus_search import set_native_subgame

    if not _ns.native_subgame_available():
        _ns.enable()
    assert _ns.native_subgame_available(), "native subgame unavailable (need the built .pyd + EMD blob)"
    set_native_subgame(True)

    snap = load_snapshot()
    log(f"snapshot infosets: {len(snap):,}  SMOKE={SMOKE} SKIP_REF={SKIP_REF} KS={KS} KREF={KREF}")

    # ---- corpus ----
    river = build_river_corpus()
    live = build_live_probe_corpus(15)
    mw = build_multiway_flop_corpus(snap, want=MW_WANT, max_hands=(60 if SMOKE else 600), seed=77)
    if SMOKE:
        river, live, mw = river[:2], live[:2], mw[:2]
    corpus = river + live + mw
    log(f"corpus: {len(corpus)} states  (river={len(river)} live_probe={len(live)} mw_flop={len(mw)})")
    if len(mw) < (2 if SMOKE else 10):
        log(f"WARNING: only {len(mw)} multiway flop states (< target); proceeding")

    sv = build_solver(snap)

    # Warm the native engine once (blueprint marshal + EMD blob) so state 1 doesn't pay it.
    try:
        from pokerbot.engine.jax_weva_encode import _POSTFLOP_NUM_BUCKETS
        t0 = time.perf_counter()
        _ns.warm_subgame_engine(sv.adapter, num_buckets=int(_POSTFLOP_NUM_BUCKETS),
                                max_playout_depth=int(sv.config.leaf.max_playout_depth))
        log(f"native engine warmed in {(time.perf_counter()-t0)*1000:.0f}ms")
    except Exception as e:  # noqa: BLE001
        log(f"warm-up skipped: {e!r}")

    results = [{"id": it["id"], "cls": it["cls"], "street": it["street"],
                "root": it["root"], "pbs": it["pbs"],
                "q": it.get("q"), "q_acts": it.get("q_acts"), "v_br": it.get("v_br"),
                "pot_bb": it.get("pot_bb"), "n_live": it.get("n_live"),
                "fixed": {}, "budget": None} for it in corpus]
    meta = {
        "spec": "artifacts/track2_search_certification_design.md §C S1",
        "git_head": os.popen("git rev-parse HEAD").read().strip(),
        "config": "engine_ab_h2h._DEPLOYED_BASELINE (deployed, native subgame ON)",
        "KS": KS, "KREF": KREF, "seed": SEED,
        "live_budget_ms": LIVE_BUDGET_MS, "arena_budget_ms": ARENA_BUDGET_MS,
        "budget_cap": BUDGET_CAP, "smoke": SMOKE,
        "n_states": len(corpus), "n_river": len(river), "n_live_probe": len(live),
        "n_mw_flop": len(mw), "started": time.strftime("%F %T"),
    }

    # ---- PHASE A: fixed-K sweep (non-reference) + budget-fit; incremental write ----
    n = len(corpus)
    for si, it in enumerate(corpus):
        r = results[si]
        for K in KS:
            probs, iters, ms, served = solve_fixed(sv, it, K)
            r["fixed"][str(K)] = {"probs": [round(float(x), 6) for x in probs],
                                  "argmax": int(np.argmax(probs)), "iters": iters,
                                  "wall_ms": round(ms, 1), "served": served}
        # budget-fit envelopes
        kl, ml, bbl = solve_budget(sv, it, LIVE_BUDGET_MS)
        ka, ma, bba = solve_budget(sv, it, ARENA_BUDGET_MS)
        r["budget"] = {
            "live_2500": {"k_main": kl, "wall_ms": round(ml, 1), "budget_bound": bbl},
            "arena_800": {"k_main": ka, "wall_ms": round(ma, 1), "budget_bound": bba},
        }
        write_out(meta, results, has_ref=False)
        pct = 100.0 * (si + 1) / n
        el = time.time() - _T_START
        eta = el / (si + 1) * (n - si - 1)
        log(f"[A {pct:5.1f}%] {it['id']:>22s} cls={it['cls']:<10s} "
            f"K{KS[-1]} wall={r['fixed'][str(KS[-1])]['wall_ms']:.0f}ms "
            f"Kmain(live={kl},arena={ka}) | elapsed {el/60:.1f}m ETA {eta/60:.1f}m")

    if SKIP_REF:
        write_out(meta, results, has_ref=False)
        log("SKIP_REF set — wrote partial (S1c full; S1a/S1b partial). Stopping before K=50000.")
        return 0

    # ---- PHASE B: K=50000 reference. Cheap classes (live_probe, mw_flop) FIRST so the non-river
    # reference lands in ~2 min; the expensive river reference (worst-case per-iter class) runs last,
    # and every state is written incrementally so a mid-run kill preserves all earlier references. ----
    order = sorted(range(n), key=lambda i: 0 if corpus[i]["cls"] != "river" else 1)
    done_b = 0
    for si in order:
        it, r = corpus[si], results[si]
        probs, iters, ms, served = solve_fixed(sv, it, KREF)
        r["fixed"][str(KREF)] = {"probs": [round(float(x), 6) for x in probs],
                                 "argmax": int(np.argmax(probs)), "iters": iters,
                                 "wall_ms": round(ms, 1), "served": served}
        done_b += 1
        # has_ref becomes True only once every state has its reference (so gates are computed on the
        # full corpus); until then keep writing the Phase-A partial view.
        write_out(meta, results, has_ref=(done_b == n))
        pct = 100.0 * done_b / n
        el = time.time() - _T_START
        eta = el / done_b * (n - done_b)
        log(f"[B {pct:5.1f}%] {it['id']:>22s} cls={it['cls']:<10s} K{KREF} wall={ms:.0f}ms "
            f"| elapsed {el/60:.1f}m ETA {eta/60:.1f}m")

    meta["finished"] = time.strftime("%F %T")
    write_out(meta, results, has_ref=True)
    gates = compute_gates(results, has_ref=True)
    log("=== S1 GATE VERDICTS ===")
    for g in ("S1a", "S1b", "S1c"):
        log(f"  {g}: {json.dumps(gates[g])[:300]}")
    log(f"wrote {OUT}")
    return 0


