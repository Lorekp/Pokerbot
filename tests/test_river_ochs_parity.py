"""River OCHS cross-language parity gate (blueprint-v2).

The trainer (tools/battery_native/src/river_ochs.rs) writes river blueprint rows under the
OCHS nearest-centroid bucket; the Python serve path (pokerbot/encoding/river_ochs.py) must
reproduce it EXACTLY or serve hits wrong-semantics rows. Both sides re-derive the shared
golden file (data/abstraction/river_ochs_160.golden.tsv, generated by
`cargo run --release --example river_ochs_fit`); the Rust half of the chain is
`cargo test river_ochs` (golden_parity_if_present).

Skips cleanly when the fitted artifacts are absent (pre-fit checkouts).
"""

from __future__ import annotations

import os

import pytest

_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
_BLOB = os.path.join(_ROOT, "data", "abstraction", "river_ochs_160.rochs")
_GOLDEN = os.path.join(_ROOT, "data", "abstraction", "river_ochs_160.golden.tsv")


def _rows():
    with open(_GOLDEN, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            yield [int(x) for x in line.split()]


@pytest.mark.skipif(
    not (os.path.exists(_BLOB) and os.path.exists(_GOLDEN)),
    reason="river OCHS artifacts not fitted",
)
def test_python_matches_golden():
    from pokerbot.encoding.river_ochs import RiverOchs

    t = RiverOchs.load(_BLOB)
    n = 0
    for f in _rows():
        assert len(f) == 8
        got = t.bucket((f[0], f[1]), f[2:7])
        assert got == f[7], f"golden mismatch at row {n}: {f} -> {got}"
        n += 1
    assert n >= 64, f"golden file suspiciously small ({n} rows)"


@pytest.mark.skipif(not os.path.exists(_BLOB), reason="river OCHS artifacts not fitted")
def test_sha256_sidecar_matches():
    import hashlib

    sidecar = _BLOB + ".sha256"
    assert os.path.exists(sidecar), "river OCHS blob must carry a .sha256 sidecar (ship gate)"
    with open(_BLOB, "rb") as f:
        actual = hashlib.sha256(f.read()).hexdigest()
    with open(sidecar, encoding="utf-8") as f:
        expected = f.read().strip().split()[0]
    assert actual == expected


@pytest.mark.skipif(not os.path.exists(_BLOB), reason="river OCHS artifacts not fitted")
def test_non_river_spots_return_minus_one():
    from pokerbot.encoding.river_ochs import RiverOchs

    t = RiverOchs.load(_BLOB)
    assert t.bucket((51, 47), [43, 39, 35]) == -1  # flop
    assert t.bucket((51, 47), [43, 39, 35, 31]) == -1  # turn
    assert t.bucket((-1, 47), [43, 39, 35, 31, 27]) == -1  # invalid hole
